    """
    Get the Fragmentation Change statistics.    
    """
    
    # Land stats computation
    group_land = [range(0,101), [101, 105, 106], [102]]
    ch_matrix_land, tot_land_A, tot_land_B = aggregate_change_matrix(ch_matrix, group_land)
    
    fgrnd_AB = ch_matrix_land[0,0]
    Uarea_AB = ch_matrix_land[0:2,0:2].sum()
    
    tots_land_A = ch_matrix_land.sum(axis=1)
    fgrnd_A = tots_land_A[0]
    bgrTT_A = tots_land_A[1]
    bgrnd_A = ch_matrix[101, :].sum()
    bgsp3_A = ch_matrix[105, :].sum()
    bgsp4_A = ch_matrix[106, :].sum() 
    miss_A = tots_land_A[2]

    tots_land_B = ch_matrix_land.sum(axis=0)
    fgrnd_B = tots_land_B[0]
    bgrTT_B = tots_land_B[1]
    bgrnd_B = ch_matrix[:, 101].sum()
    bgsp3_B = ch_matrix[:, 105].sum()
    bgsp4_B = ch_matrix[:, 106].sum()     
    miss_B = tots_land_B[2]

    # Class stats computation
    group_clas = [[101, 105, 106], range(0,10), range(10,40), range(40,60), range(60,90), range(90,101)]
    ch_matrix_clas, tot_clas_A, tot_clas_B  = aggregate_change_matrix(ch_matrix, group_clas)
    
    tots_class_A = ch_matrix_clas.sum(axis=1)
    rare_A = tots_class_A[1]
    patchy_A = tots_class_A[2]
    trans_A = tots_class_A[3]
    domin_A = tots_class_A[4]
    inter_A = tots_class_A[5]

