def frag_change(
    in_tiff_t1,
    in_tiff_t2,
    outdir=None,
    statists=True,
    stat_files=True,
    verb=False
    ):
    """
    Performs a comparative Fragmentation Change analysis using two structural 
    fragmentation rasters (Time A/T1 and Time B/T2) generated by Guidos.

    It computes pixel-by-pixel class transitions across a 7-tier matrix overlay, 
    tracks localized delta variations, and compiles comprehensive global matrix 
    statistics reporting land-cover and connectivity class dynamics.

    Parameters
    ----------
    in_tiff_t1 : str or Path
        Path to the initial time-step Fragmentation GeoTIFF (Time A / T1). 
        Must be a valid Guidos 'GTB_FOS' output.
    in_tiff_t2 : str or Path
        Path to the subsequent time-step Fragmentation GeoTIFF (Time B / T2). 
        Must be a valid Guidos 'GTB_FOS' output matching T1's spatial extent.
    outdir : str or Path, optional
        Directory for generated output files. Defaults to the directory of 
        the initial input file (`in_tiff_t1`).
    statists : bool, optional
        If True (default), computes and returns change transition statistics.
    stat_files : bool, optional
        If True (default) and `statists` is True, writes statistics reports 
        to explicit `.txt`, `.csv`, and `.png` histogram files.
    verb : bool, optional
        If True, prints execution pipeline progress messages. Default is False.

    Returns
    -------
    dict or None
        If `statists` is True, returns a nested dictionary containing:
        - 'output paths' (dict or None): Paths to generated files
          ('path tif', 'path txt', 'path csv', 'path png').
        - 'input stats' (dict): Extracted raw pixel frequencies for T1 and T2 
          (Foreground, Background, Missing, Special classes).
        - 'output stats' (dict): Class frequency mappings, connectivity indices 
          (avcon, fad_av) for both time steps, and aggregated transition matrices.
        Returns None if `statists` is False.

    Output Files
    ------------
    - FOS_change.tif : Categorical fragmentation change layer grid.
    - FOS_change.txt : Detailed structural analysis change matrix text report.
    - FOS_change.csv : Tabular cell count statistics with delta values.
    - FOS_change.png : Connectivity change frequency distribution bar chart.
    """
    start_time = time.time()
    
    # Log
    utils.log_msg(verb, "[   START   ]  Verifying input raster...")

    # Initialize Paths and Metadata
    in_tiff1 = Path(in_tiff_t1)
    in_tiff2 = Path(in_tiff_t2)
    outdir = Path(outdir) if outdir else in_tiff1.parent
    outname = "FOS_change"
    info1 = utils.get_raster_info(in_tiff1)
    info2 = utils.get_raster_info(in_tiff2)

    # Input Geotiff validations
    checks.validate_fchmaps_input(info1, info2)
    
    # Log
    utils.log_msg(verb, "[    OK     ]  Input raster verified.")

    try:
        # Log
        utils.log_msg(verb, "[   START   ]  Computing Fragmentation Change...")
        
        # Output Geotiff info
        tag_descr = info1["tag"]
        tag_descr = tag_descr.replace("GTB_FOS","GTB_FOSCHANGE")
        cmap_path = TEMPL_DIR / "frag_change_colormap.txt"
        out_tiff = outdir / f"{outname}.tif"
        _, color_map = utils.get_colormap(cmap_path)
        tags = {"TIFFTAG_IMAGEDESCRIPTION": tag_descr,
                "TIFFTAG_SOFTWARE": "pyGuidos"}
        
        # Compute Frag Change
        change_matrix = np.zeros((107, 107), dtype=np.int64)
        with rasterio.open(in_tiff1) as src_a, rasterio.open(in_tiff2) as src_b:
            out_profile = info1["profile"]
            out_profile.update(tiled=True)
        
            # BigTIFF threshold optimization
            estimated_gb = (info1["rows"] * info1["cols"]) / (1024**3)
            out_profile.update(bigtiff="YES" if estimated_gb > 3.8 else "NO")
        
            with rasterio.open(out_tiff, "w", **out_profile) as dst:
                for ij, window in src_a.block_windows():
                    chunk_a = src_a.read(1, window=window)
                    chunk_b = src_b.read(1, window=window)
        
                    # Computes raster AND statistics
                    chunk_out = engine.compute_fos_change(chunk_a, 
                                                          chunk_b, 
                                                          change_matrix, 
                                                          statists)
                    # Write the chunk output
                    dst.write(chunk_out, 1, window=window)
        
                dst.colorinterp = [ColorInterp.palette]
                dst.write_colormap(1, color_map)
                dst.update_tags(**tags)
     
        # Log
        utils.log_msg(verb, "[    OK     ]  Fragmentation Change computed.")
 
        # Statistics and Reporting
        stats_dict = None
        if statists:
            utils.log_msg(verb, "[   START   ]  Generating statistics...")        
            
            # Computing statistics
            stats_dict = _get_frag_change_stats(frag_chan_tiff = out_tiff, 
                                                ch_matrix = change_matrix,
                                                tiff1 = in_tiff1,
                                                tiff2 = in_tiff2,
                                                out_file = stat_files,
                                                out_dir = outdir)    
            
        # Computational time and log
        time_str = utils.running_time(start_time, time.time())
        
        if statists:
            txt_file = txt_file = outdir / f'{outname}.txt'
            utils.update_time_line(txt_file, time_str)
            utils.log_msg(verb, "[    OK     ]  Statistics complete")
        
        utils.log_msg(verb, f"\n>>> Fragmentation Change task finished in {time_str}") 

        return stats_dict

    except Exception as e:
        print(f"Error during run: {e}")
        raise # Still show the error




