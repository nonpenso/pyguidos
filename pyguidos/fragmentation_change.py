def aggregate_change_matrix(matrix, groupings):
    """Aggregates a change matrix and calculates the totals for File A and File B.

    Parameters:
    - matrix (np.ndarray): The original square matrix (e.g., 11x11).
    - groupings (list of lists): The custom class groupings.

    Returns:
    - new_matrix (np.ndarray): The aggregated square matrix.
    - file_a_totals (np.ndarray): Total pixels per group in File A (Row sums).
    - file_b_totals (np.ndarray): Total pixels per group in File B (Col sums).
    """
    num_new_classes = len(groupings)
    new_matrix = np.zeros((num_new_classes, num_new_classes), dtype=matrix.dtype)

    # 1. Compute the aggregated matrix
    for new_row, row_indices in enumerate(groupings):
        for new_col, col_indices in enumerate(groupings):
            sub_matrix = matrix[np.ix_(row_indices, col_indices)]
            new_matrix[new_row, new_col] = sub_matrix.sum()

    # 2. Calculate totals directly from the newly aggregated matrix
    # Axis 1 sums across columns (collapsing rows -> File A totals)
    file_a_totals = new_matrix.sum(axis=1)

    # Axis 0 sums down rows (collapsing columns -> File B totals)
    file_b_totals = new_matrix.sum(axis=0)

    return new_matrix, file_a_totals, file_b_totals